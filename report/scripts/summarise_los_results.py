#!/usr/bin/env python3
"""Regenerate report tables and aggregate figures from the pinned LOS CSVs."""
import csv
from collections import defaultdict
import json
import math
import os
from pathlib import Path
import statistics as st

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'contributions' / 'los-uncertainty'
METHODS = ['SA', 'Tabu', 'Tabu+SA', 'GA (p_mut=1/n)']
LABEL = {'SA': 'SA', 'Tabu': 'Tabu', 'Tabu+SA': 'Hybrid',
         'GA (p_mut=1/n)': r'GA ($p_{\mathrm{mut}}=1/n$)'}


def read(name):
    with (DATA / name).open(newline='') as handle:
        return list(csv.DictReader(handle))


def select(rows, **filters):
    return [r for r in rows if all(r.get(k) == str(v) for k, v in filters.items())]


def mean(rows, key):
    return st.mean(float(r[key]) for r in rows)


def paired(rows, method):
    nominal = {r['seed']: float(r['mc_mean']) for r in select(rows, method=method, mode='nominal')}
    upper = {r['seed']: float(r['mc_mean']) for r in select(rows, method=method, mode='upper')}
    assert set(nominal) == set(upper) and len(nominal) == 10
    values = [upper[s] - nominal[s] for s in sorted(nominal)]
    return st.mean(values), st.stdev(values) / math.sqrt(len(values))


def write_table(name, caption, label, columns, header, rows):
    text = ('% Generated by scripts/summarise_los_results.py; do not edit manually.\n'
            '\\begin{table}[tbp]\n\\centering\n\\small\n'
            + '\\caption{' + caption + '}\n\\label{' + label + '}\n'
            + '\\begin{tabularx}{\\textwidth}{@{}' + columns + '@{}}\n\\toprule\n'
            + header + ' \\\\\n\\midrule\n' + '\n'.join(rows)
            + '\n\\bottomrule\n\\end{tabularx}\n\\end{table}\n')
    (ROOT / 'tables' / name).write_text(text)


def main():
    (ROOT / 'tables').mkdir(exist_ok=True)
    (ROOT / 'figures').mkdir(exist_ok=True)
    campaigns = {}
    for name, filename in [('base', 'results_los_v3_base.csv'), ('split', 'results_los_v3_v2res.csv')]:
        all_rows = read(filename)
        # Tracking and noise are evaluations of the same saved plan, not new runs.
        rows = select(all_rows, scale='large', tracking='trunc', noise='floor')
        ids = [(r['seed'], r['method'], r['mode']) for r in rows]
        assert len(ids) == len(set(ids)), 'Repeated runs must not inflate the sample size'
        assert {r['seed'] for r in rows} == {str(s) for s in range(42, 52)}
        for r in all_rows:
            expected = 5 * float(r['ov_vac']) + 3 * float(r['ov_lits']) + .05 * float(r['balance'])
            assert math.isclose(expected, float(r['nominal_cost']), rel_tol=1e-10, abs_tol=1e-7)
            assert math.isclose(float(r['mc_mean']) - float(r['nominal_cost']),
                                float(r['cost_increase']), rel_tol=1e-8, abs_tol=1e-7)
        campaigns[name] = rows

    quality, quality_rows = {}, []
    for campaign, title in [('base', r'One 480-minute session per speciality-day'),
                            ('split', r'Two 240-minute sessions per speciality-day')]:
        quality_rows.append(r'\multicolumn{4}{@{}l}{\emph{' + title + r'}} \\')
        quality[campaign] = {}
        for method in METHODS:
            rows = select(campaigns[campaign], method=method, mode='nominal')
            cost, bound, seconds = mean(rows, 'nominal_cost'), mean(rows, 'lb_vac_cost'), mean(rows, 'time_s')
            assert bound == 5190 and len(rows) == 10
            sd = st.stdev(float(r['nominal_cost']) for r in rows)
            gap = 100 * (cost / bound - 1)
            quality[campaign][method] = dict(cost=cost, sd=sd, gap=gap, time_s=seconds)
            quality_rows.append(f"{LABEL[method]} & ${cost:.1f} \\pm {sd:.1f}$ & {gap:.2f}\\% & {seconds:.3f} " + r'\\')
        if campaign == 'base':
            quality_rows.append(r'\midrule')
    write_table('los-quality.tex',
                'Large workload: point-LOS schedule cost (mean $\\pm$ SD over ten seeds), '
                'gap to the session-overload lower bound of 5190, and mean planning time. '
                'These are gaps to a lower bound, not certified gaps to the true optimum.',
                'tab:los-quality', 'Yrrr', r'Method & Cost & Bound gap & Time (s)', quality_rows)

    delta_rows, deltas = [], {}
    for method in METHODS:
        deltas[method] = {name: paired(rows, method) for name, rows in campaigns.items()}
        a, ae = deltas[method]['base']; b, be = deltas[method]['split']
        delta_rows.append(f"{LABEL[method]} & ${a:+.1f} \\pm {ae:.1f}$ & ${b:+.1f} \\pm {be:.1f}$ " + r'\\')
    write_table('los-robustness.tex',
                'Paired change in scenario-mean cost, upper-bound planning minus point planning '
                '(mean $\\pm$ SE across ten seeds). Negative values favour upper-bound planning. '
                'Floor-noise scenarios and horizon-truncated bed tracking are used in both configurations.',
                'tab:los-robustness', 'Yrr', r'Method & $1\times480$ min & $2\times240$ min', delta_rows)

    legacy = read('results_mc.csv')
    names = [('SA','Recuit simule'),('Tabu','Tabou'),('Hybrid','Tabou x Recuit'),
             ('GA (default)','Genetique'),('ACO','Fourmis (ACO)')]
    legacy_rows = []
    legacy_summary = {}
    for display, method in names:
        large = select(legacy, scale='large', mode='nominal', method=method)
        assert len(large) == 10
        sd = st.stdev(float(r['nominal_cost']) for r in large)
        small_time = mean([r for r in legacy if r['scale']=='small' and r['method']==method and r['mode'] in ('nominal','upper')], 'time_s')
        large_time = mean([r for r in legacy if r['scale']=='large' and r['method']==method and r['mode'] in ('nominal','upper')], 'time_s')
        legacy_summary[display] = dict(cost=mean(large, 'nominal_cost'), small_time=small_time, large_time=large_time)
        legacy_rows.append(f"{display} & ${mean(large,'nominal_cost'):.1f} \\pm {sd:.1f}$ & {small_time:.2f} & {large_time:.2f} " + r'\\')
    write_table('los-legacy.tex',
                'Original five-method campaign: nominal cost for the large workload (mean $\\pm$ SD, '
                'ten seeds), and planning time averaged over point and upper-bound modes. '
                'GA uses its default mutation probability here; ACO was not run in the later split-session campaign.',
                'tab:los-legacy', 'Yrrr', r'Method & Large cost & Small (s) & Large (s)', legacy_rows)

    matched = select(read('results_los_v3_matched.csv'), mode='nominal', tracking='trunc', noise='floor')
    assert {r['n_patients'] for r in matched} == {'363'}
    assert all(float(r['lb_vac_cost']) == 0 for r in matched)
    matched_summary = {m: {k: mean(select(matched,method=m),k) for k in ('nominal_cost','ov_vac','ov_lits')}
                       for m in METHODS}
    load = select(read('results_los_v3_load.csv'), mode='nominal', tracking='trunc', noise='floor')
    assert sorted(set(float(r['bloc_load']) for r in load)) == [.8,.93,.98,1.1]
    for r in load:
        assert r['beds']=='42' and r['vac_split']=='2'

    os.environ.setdefault('MPLCONFIGDIR', '/tmp/report-los-matplotlib')
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    import numpy as np
    plt.rcParams.update({'font.size':10, 'axes.spines.top':False, 'axes.spines.right':False,
                         'savefig.dpi':180})
    x=np.arange(len(METHODS)); width=.34
    fig, ax=plt.subplots(figsize=(7.2,3.5))
    for name, offset, color, label in [('base',-width/2,'#275D8C','1 x 480 min'),
                                       ('split',width/2,'#C66C2E','2 x 240 min')]:
        values=[quality[name][m]['gap'] for m in METHODS]
        errors=[100*quality[name][m]['sd']/5190 for m in METHODS]
        ax.bar(x+offset,values,width,yerr=errors,capsize=3,color=color,label=label)
    ax.set_xticks(x,['SA','Tabu','Hybrid','GA (1/n)'])
    ax.set_ylabel('Gap to session-overload lower bound (%)')
    ax.legend(frameon=False); ax.grid(axis='y',alpha=.2); ax.set_axisbelow(True)
    fig.tight_layout(); fig.savefig(ROOT/'figures/los-granularity.png'); plt.close(fig)

    fig, ax=plt.subplots(figsize=(7.2,3.5))
    for name,offset,color,label in [('base',-width/2,'#275D8C','1 x 480 min'),
                                   ('split',width/2,'#C66C2E','2 x 240 min')]:
        values=[deltas[m][name][0] for m in METHODS]; errors=[deltas[m][name][1] for m in METHODS]
        ax.errorbar(x+offset,values,yerr=errors,fmt='o',capsize=4,color=color,label=label)
    ax.axhline(0,color='#444444',linewidth=.8)
    ax.set_xticks(x,['SA','Tabu','Hybrid','GA (1/n)'])
    ax.set_ylabel('Scenario-mean cost: upper minus point')
    ax.legend(frameon=False); ax.grid(axis='y',alpha=.2); ax.set_axisbelow(True)
    fig.tight_layout(); fig.savefig(ROOT/'figures/los-uncertainty.png'); plt.close(fig)

    fig, ax=plt.subplots(figsize=(7.2,3.5))
    for method,color in zip(METHODS,['#275D8C','#377A56','#C66C2E','#76538F']):
        ratios=sorted(set(float(r['bloc_load']) for r in load))
        groups=[select(load,method=method,bloc_load=str(ratio)) for ratio in ratios]
        assert all(len(g)==5 for g in groups)
        ax.errorbar(ratios,[mean(g,'planned_cost') for g in groups],
                    yerr=[st.stdev(float(r['planned_cost']) for r in g) for g in groups],
                    marker='o',capsize=3,label=('Hybrid' if method=='Tabu+SA' else method),color=color)
    ax.set_xlabel('Target bottleneck-speciality operating-block load')
    ax.set_ylabel('Planned cost (mean +/- SD)')
    ax.legend(frameon=False,ncol=2); ax.grid(alpha=.2); ax.set_axisbelow(True)
    fig.tight_layout(); fig.savefig(ROOT/'figures/los-block-load.png'); plt.close(fig)

    summary={'quality':quality,'paired_upper_minus_point':deltas,'legacy':legacy_summary,
             'matched':matched_summary,'validation':{'cost_identities_checked':True,
             'paired_seeds':10,'load_seeds':5,'source':'d2dc2260d7b9c4b1ed2a49e6889b08fe0c484888'}}
    (ROOT/'tables/los-summary.json').write_text(json.dumps(summary,indent=2)+'\n')
    print(json.dumps(summary,indent=2))


if __name__=='__main__':
    main()
